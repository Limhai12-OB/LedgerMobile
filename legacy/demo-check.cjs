// Run: node demo-check.cjs <path-to-jsdom>
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { JSDOM } = require(process.argv[2] || 'jsdom');
const html = fs.readFileSync(__dirname + '/ledgervision_app.html', 'utf8');
const dom = new JSDOM(html, { runScripts: 'dangerously', url: 'http://localhost/', beforeParse(w) {
  w.scrollTo = () => {};
  w.HTMLDialogElement.prototype.showModal = function() { this.open = true; };
  w.HTMLDialogElement.prototype.close = function() { this.open = false; };
}});
const w = dom.window, d = w.document;
const click = s => { assert.ok(d.querySelector(s), s); d.querySelector(s).click(); };
assert.match(d.querySelector('.stats').textContent, /25,400/);
assert.match(d.querySelector('.stats').textContent, /16,200/);
click('[data-page="transactions"]');
assert.equal(d.querySelectorAll('[data-edit]').length, 18);
const search = d.getElementById('search'); search.value = 'Angkor'; search.dispatchEvent(new w.Event('input'));
assert.equal(d.querySelectorAll('[data-edit]').length, 3);
click('[data-add]');
const form = d.getElementById('transaction-form');
form.elements.name.value = 'Demo QA purchase'; form.elements.amount.value = '25';
form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
assert.match(d.getElementById('tx-list').textContent, /Demo QA purchase/);
assert.equal(JSON.parse(w.localStorage.getItem('ledgervision-demo-v2')).length, 109);
const newButton = [...d.querySelectorAll('[data-edit]')].find(el => el.textContent.includes('Demo QA purchase'));
newButton.click(); d.getElementById('transaction-form').elements.amount.value = '50';
d.getElementById('transaction-form').dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(JSON.parse(w.localStorage.getItem('ledgervision-demo-v2')).find(t => t.name === 'Demo QA purchase').amount, 50);
click('[data-page="home"]'); assert.match(d.querySelector('.stats').textContent, /5,150/);
const role = d.getElementById('role'); role.value = 'manager'; role.dispatchEvent(new w.Event('change'));
assert.ok(d.getElementById('branch').disabled);
click('[data-page="transactions"]'); assert.equal(d.querySelectorAll('[data-edit]').length, 7);
click('[data-page="ai"]'); click('[data-ask="Compare my branches"]');
assert.match(d.getElementById('messages').textContent, /viewing BKK only/);
click('[data-page="capture"]'); click('[data-sample]');
assert.equal(d.getElementById('transaction-form').elements.amount.value, '125'); click('[data-close]');
click('[data-page="reports"]'); assert.match(d.getElementById('content').textContent, /Spending breakdown/);
click('[data-page="transactions"]');
[...d.querySelectorAll('[data-edit]')].find(el => el.textContent.includes('Demo QA purchase')).click();
click('[data-delete]'); click('#confirm-delete');
assert.equal(JSON.parse(w.localStorage.getItem('ledgervision-demo-v2')).length, 108);
click('[data-page="settings"]'); click('[data-reset]'); click('#confirm-reset');
assert.equal(JSON.parse(w.localStorage.getItem('ledgervision-demo-v2')).length, 108);
console.log('PASS: totals, search, add, edit, persistence, role scope, AI scope, receipt sample, reports, delete, reset');
w.close();
